#!/bin/sh
# scripts/check-tracked-data.sh
#
# Проверяет: не отслеживает ли git прямо сейчас реальные файлы модов/базы
# (data/*.db, public/uploads/*). Такое возможно, если они были закоммичены
# ДО того, как появился .gitignore — сам .gitignore не трогает файлы,
# которые git уже отслеживает, он только не даёт добавить НОВЫЕ.
#
# Запускать в корне проекта, там же, где лежит .git — то есть на VPS, там,
# где реальные данные, а не на другой машине с возможно устаревшей копией.
#
# Использование:
#   sh scripts/check-tracked-data.sh          — только проверить
#   sh scripts/check-tracked-data.sh --fix    — проверить и сразу убрать
#                                                из git (файлы на диске не
#                                                трогает, только index)

set -e

if [ ! -d .git ]; then
  echo "Здесь нет .git — запустите скрипт из корня проекта (где лежит .git)."
  exit 1
fi

TRACKED=$(git ls-files data public/uploads 2>/dev/null | grep -v '\.gitkeep$' || true)

if [ -z "$TRACKED" ]; then
  echo "Всё чисто: git не отслеживает ни одного файла в data/ или public/uploads/,"
  echo "кроме .gitkeep-заглушек. Новые коммиты этих папок не коснутся."
  exit 0
fi

echo "ВНИМАНИЕ: git прямо сейчас отслеживает эти файлы (при следующем"
echo "коммите/пуше/пулле их состояние может измениться или они могут пропасть):"
echo "$TRACKED"
echo

if [ "$1" != "--fix" ]; then
  echo "Чтобы убрать их из-под git (файлы на диске останутся нетронутыми!),"
  echo "запустите: sh scripts/check-tracked-data.sh --fix"
  exit 0
fi

echo "Убираю из индекса git (--cached — только из git, на диске файлы остаются)..."
echo "$TRACKED" | xargs -r git rm --cached -q

git add .gitignore
git commit -m "Данные модов и база больше не хранятся в git" -q
echo
echo "Готово. Осталось: git push — и с этого момента коммиты/пуллы данные не тронут."
echo "Делайте это именно на той машине, где лежат настоящие файлы (обычно VPS) —"
echo "тогда файлы просто перестанут отслеживаться, физически никуда не денутся."
